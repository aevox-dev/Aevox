"""Keep a generated CMake source manifest in sync with application files."""

from __future__ import annotations

import re
from pathlib import Path

SOURCE_SUFFIXES = {".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx", ".inl"}
SOURCE_TOKEN = re.compile(r"(?<![A-Za-z0-9_./+-])([A-Za-z0-9_./+-]+\.(?:c|cc|cpp|cxx|h|hh|hpp|hxx|inl))(?![A-Za-z0-9_./+-])")
SUBDIRECTORY = re.compile(r'add_subdirectory\s*\(\s*"?([A-Za-z0-9_./+-]+)', re.IGNORECASE)
INCLUDE = re.compile(r'include\s*\(\s*"?([A-Za-z0-9_./+-]+\.cmake)', re.IGNORECASE)
MANIFEST = Path("cmake/AevoxSources.cmake")


def _project_files(root: Path) -> list[Path]:
    """Find application code recursively while leaving the dependency untouched."""
    paths = []
    for directory in (root / "src", root / "include"):
        if directory.is_dir():
            paths.extend(path for path in directory.rglob("*")
                         if path.is_file() and not path.is_symlink()
                         and path.suffix.lower() in SOURCE_SUFFIXES)
    return sorted(paths)


def _manual_sources(root: Path) -> set[Path]:
    """Read literal filenames from every application CMake file, at any depth.

    CMake variables and generator expressions cannot be resolved statically.
    A file named explicitly in a CMake file is left under that file's control.
    """
    referenced: set[Path] = set()
    pending = [root / "CMakeLists.txt"]
    visited: set[Path] = set()
    while pending:
        cmake = pending.pop().resolve()
        if cmake in visited or not cmake.is_file() or cmake.is_symlink() or cmake == root / MANIFEST:
            continue
        if not cmake.is_relative_to(root) or any(
            part in {"vendor", "build", ".git", "vcpkg_installed"} for part in cmake.relative_to(root).parts
        ):
            continue
        visited.add(cmake)
        content = "\n".join(line.partition("#")[0] for line in cmake.read_text(encoding="utf-8").splitlines())
        for token in SOURCE_TOKEN.findall(content):
            path = (cmake.parent / token).resolve()
            if path.is_relative_to(root):
                referenced.add(path)
        pending.extend((cmake.parent / directory / "CMakeLists.txt") for directory in SUBDIRECTORY.findall(content))
        pending.extend((cmake.parent / include) for include in INCLUDE.findall(content))
    return referenced


def prepare_project(root: Path) -> list[str]:
    """Write an idempotent manifest for all unlisted C/C++ files.

    Each entry is absolute from ``PROJECT_SOURCE_DIR`` so nested CMake files
    and the current working directory cannot change its meaning.
    """
    root = root.resolve()
    if not (root / "CMakeLists.txt").is_file() or not (root / "src/CMakeLists.txt").is_file():
        raise ValueError(f"{root} is not an Aevox CLI project")
    manual = _manual_sources(root)
    paths = [path.relative_to(root).as_posix() for path in _project_files(root) if path.resolve() not in manual]
    lines = [
        "# Generated by `aevox prepare`. Edit application CMakeLists.txt for custom targets.",
        "# Files named explicitly in other CMake files are omitted here.",
        "target_sources(${PROJECT_NAME} PRIVATE",
    ]
    lines.extend(f'    "${{PROJECT_SOURCE_DIR}}/{path}"' for path in paths)
    lines.extend([")", ""])
    destination = root / MANIFEST
    destination.parent.mkdir(parents=True, exist_ok=True)
    contents = "\n".join(lines)
    if not destination.exists() or destination.read_text(encoding="utf-8") != contents:
        destination.write_text(contents, encoding="utf-8")
    return paths
